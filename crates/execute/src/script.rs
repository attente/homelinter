//! Platform script export: POSIX shell (linux, macOS) and PowerShell
//! (Windows) scripts built from a validated execution plan.
//!
//! The script repeats the executor's safe defaults: it aborts on unexpected
//! source or destination state rather than overwriting, performs moves with
//! no-clobber semantics, re-verifies content hashes before deletes that
//! have one on record, and runs dependent symlink repairs only after their
//! parent succeeds. A cross-filesystem move is refused at run time and
//! pointed at the native executor: a shell script cannot reproduce the
//! verified copy, hash check, no-replace publish, and source-removal
//! protocol safely, so exporting one would weaken safety. The native
//! executor remains authoritative, and a script can never do more than the
//! validated plan.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use homelinter_model::config::platform_name;
use homelinter_model::suggestion::{
    DependentOperation, Suggestion, SuggestionStatus, SuggestionType,
};

/// Render an export for the host platform from validated suggestions.
/// Suggestions must already be batch-validated; rejected suggestions are
/// skipped by callers and never appear here.
pub fn export_script(suggestions: &[Suggestion], platform: &str) -> Result<String, String> {
    match platform {
        "linux" | "macos" => export_posix(suggestions),
        "windows" => export_powershell(suggestions),
        other => Err(format!("unsupported export platform: {other}")),
    }
}

/// Export for the host platform.
pub fn export_host(suggestions: &[Suggestion]) -> Result<String, String> {
    export_script(suggestions, platform_name())
}

fn export_posix(suggestions: &[Suggestion]) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("#!/bin/sh\n");
    out.push_str("# Generated by homelinter. Do not edit; re-export instead.\n");
    out.push_str("set -eu\n");
    out.push_str("abort() { echo \"homelinter: $*\" >&2; exit 1; }\n\n");

    let planned = planned_moves(suggestions);
    for s in export_order(suggestions) {
        match s.suggestion_type {
            SuggestionType::Move => export_posix_move(s, &mut out)?,
            SuggestionType::Delete => export_posix_delete(s, &mut out)?,
        }
        for dep in &s.dependent_operations {
            let link = shell_quote(&dep.link_path);
            let repl = shell_quote(&exported_repair_target(s, dep, &planned));
            out.push_str(&format!(
                "[ -L {link} ] || abort \"link changed: {link}\"\n"
            ));
            out.push_str(&format!("ln -sfn {repl} {link}\n"));
        }
        out.push('\n');
    }
    Ok(out)
}

fn export_posix_move(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let src = shell_quote(&s.target);
    let dst = s
        .new_path
        .as_ref()
        .ok_or_else(|| format!("move suggestion {} lacks new_path", s.id))?;
    let dst_q = shell_quote(dst);
    let parent = Path::new(dst)
        .parent()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_default();
    let parent_q = shell_quote(&parent);
    if !s.reason.is_empty() {
        out.push_str(&format!(
            "# {}\n",
            s.reason.replace('\n', " ").replace('#', "")
        ));
    }
    out.push_str(&format!(
        "[ -e {src} ] || abort \"source missing: {src}\"\n"
    ));
    out.push_str(&format!(
        "[ ! -e {dst_q} ] || abort \"destination exists: {dst_q}\"\n"
    ));
    out.push_str(&format!("mkdir -p {parent_q}\n"));
    // Same-filesystem guard: `mv` across filesystems degrades to a plain
    // copy and delete without verification. The native executor's verified
    // copy protocol cannot be reproduced safely in a shell script, so the
    // export refuses that case at run time instead of risking data loss.
    out.push_str(&format!(
        "if [ \"$(stat -c %d {src} 2>/dev/null || stat -f %d {src})\" = \"$(stat -c %d {parent_q} 2>/dev/null || stat -f %d {parent_q})\" ]; then\n"
    ));
    out.push_str(&format!(
        "  mv -n {src} {dst_q} || abort \"move failed: {src}\"\n"
    ));
    out.push_str(&format!(
        "  [ ! -e {src} ] || abort \"source remains: {src}\"\n"
    ));
    out.push_str("else\n");
    out.push_str(&format!(
        "  abort \"cross-filesystem move is not supported in an exported script; run homelinter to execute it: {src} -> {dst_q}\"\n"
    ));
    out.push_str("fi\n");
    Ok(())
}

fn export_posix_delete(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let target = shell_quote(&s.target);
    if !s.reason.is_empty() {
        out.push_str(&format!(
            "# {}\n",
            s.reason.replace('\n', " ").replace('#', "")
        ));
    }
    out.push_str(&format!(
        "[ -e {target} ] || abort \"delete target missing: {target}\"\n"
    ));
    // Delete requires the full-content hash recorded at analysis; without
    // it the native executor refuses and the export refuses too.
    if let Some(hash_hex) = s.provenance.full_hash {
        let expected = hex::encode(hash_hex);
        // `sha256sum` is GNU coreutils and absent on stock macOS; `shasum`
        // ships with macOS (and most Perl installations). Pick whichever
        // exists so the exported delete is portable across both targets.
        out.push_str("if command -v sha256sum >/dev/null 2>&1; then\n");
        out.push_str(&format!("  actual=$(sha256sum {target} | cut -d' ' -f1)\n"));
        out.push_str("elif command -v shasum >/dev/null 2>&1; then\n");
        out.push_str(&format!(
            "  actual=$(shasum -a 256 {target} | cut -d' ' -f1)\n"
        ));
        out.push_str("else\n");
        out.push_str("  abort \"no SHA-256 tool available (need sha256sum or shasum)\"\n");
        out.push_str("fi\n");
        out.push_str(&format!(
            "[ \"$actual\" = \"{expected}\" ] || abort \"content changed since analysis: {target}\"\n"
        ));
    } else {
        return Err(format!(
            "delete suggestion {} has no recorded content hash; export refused",
            s.id
        ));
    }
    out.push_str(&format!("rm -f {target}\n"));
    Ok(())
}

/// Export order: moves before deletes, then source sort key. A duplicate
/// delete's keeper may be a move in the same script, and its keeper has to
/// reach its final path before the delete's repairs run.
fn export_order(suggestions: &[Suggestion]) -> Vec<&Suggestion> {
    let mut ordered: Vec<&Suggestion> = suggestions
        .iter()
        .filter(|s| s.status != SuggestionStatus::Rejected)
        .collect();
    ordered.sort_by_key(|s| (s.suggestion_type != SuggestionType::Move, s.sort_key()));
    ordered
}

/// Final destination of every planned move, keyed by its source path.
fn planned_moves(suggestions: &[Suggestion]) -> BTreeMap<PathBuf, PathBuf> {
    suggestions
        .iter()
        .filter(|s| s.suggestion_type == SuggestionType::Move)
        .filter(|s| s.status != SuggestionStatus::Rejected)
        .filter_map(|s| {
            let dst = s.new_path.as_ref()?;
            Some((s.target_path().to_path_buf(), PathBuf::from(dst)))
        })
        .collect()
}

/// A delete's repair points at its keeper. When that keeper is moved by the
/// same script, the keeper's final path is the only one left after the move,
/// so the repair is retargeted there; otherwise it keeps the original path.
fn exported_repair_target(
    s: &Suggestion,
    dep: &DependentOperation,
    planned: &BTreeMap<PathBuf, PathBuf>,
) -> String {
    if s.suggestion_type == SuggestionType::Delete {
        if let Some(recorded) = super::recorded_keeper(s) {
            if let Some(current) = planned.get(&recorded) {
                if let Some(replacement) = super::remap_repair_target(dep, &recorded, current) {
                    return replacement;
                }
            }
        }
    }
    dep.replacement_target.clone()
}

fn export_powershell(suggestions: &[Suggestion]) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("# Generated by homelinter. Do not edit; re-export instead.\n");
    out.push_str("$ErrorActionPreference = 'Stop'\n");
    out.push_str("function Abort([string]$msg) { Write-Error \"homelinter: $msg\"; exit 1 }\n\n");
    let planned = planned_moves(suggestions);
    for s in export_order(suggestions) {
        match s.suggestion_type {
            SuggestionType::Move => export_powershell_move(s, &mut out)?,
            SuggestionType::Delete => export_powershell_delete(s, &mut out)?,
        }
        for dep in &s.dependent_operations {
            // Windows junction/reparse repair is a documented seam; the
            // script aborts rather than guessing at link semantics.
            out.push_str(&format!(
                "# repair_symlink {dep_link} -> {dep_repl} (reparse-point repair is a seam on Windows; run homelinter instead)\n",
                dep_link = dep.link_path,
                dep_repl = exported_repair_target(s, dep, &planned),
            ));
        }
        out.push('\n');
    }
    Ok(out)
}

fn export_powershell_move(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let dst = s
        .new_path
        .as_ref()
        .ok_or_else(|| format!("move suggestion {} lacks new_path", s.id))?;
    let parent = Path::new(dst)
        .parent()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_default();
    let src = ps_quote(&s.target);
    let dst_q = ps_quote(dst);
    let parent_q = ps_quote(&parent);
    if !s.reason.is_empty() {
        out.push_str(&format!("# {}\n", s.reason.replace('\n', " ")));
    }
    out.push_str(&format!(
        "if (-not (Test-Path -LiteralPath '{src}')) {{ Abort 'source missing: {src}' }}\n"
    ));
    out.push_str(&format!(
        "if (Test-Path -LiteralPath '{dst_q}') {{ Abort 'destination exists: {dst_q}' }}\n"
    ));
    out.push_str(&format!(
        "New-Item -ItemType Directory -Force -Path '{parent_q}' | Out-Null\n"
    ));
    out.push_str(&format!(
        "Move-Item -LiteralPath '{src}' -Destination '{dst_q}'\n"
    ));
    Ok(())
}

fn export_powershell_delete(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let Some(hash_hex) = s.provenance.full_hash else {
        return Err(format!(
            "delete suggestion {} has no recorded content hash; export refused",
            s.id
        ));
    };
    let expected = hex::encode(hash_hex);
    let src = ps_quote(&s.target);
    if !s.reason.is_empty() {
        out.push_str(&format!("# {}\n", s.reason.replace('\n', " ")));
    }
    out.push_str(&format!(
        "if (-not (Test-Path -LiteralPath '{src}')) {{ Abort 'delete target missing: {src}' }}\n"
    ));
    out.push_str(&format!(
        "$h = (Get-FileHash -Algorithm SHA256 -LiteralPath '{src}').Hash.ToLower()\n"
    ));
    out.push_str(&format!(
        "if ($h -ne '{expected}') {{ Abort 'content changed since analysis: {src}' }}\n"
    ));
    out.push_str(&format!("Remove-Item -LiteralPath '{src}'\n"));
    Ok(())
}

/// Single-quote a path for POSIX shells: `'` becomes `'\''`.
fn shell_quote(p: &str) -> String {
    format!("'{}'", p.replace('\'', "'\\''"))
}

/// Escape a path for a single-quoted PowerShell string: `'` becomes `''`.
/// Callers wrap the result in single quotes.
fn ps_quote(p: &str) -> String {
    p.replace('\'', "''")
}

#[cfg(test)]
mod tests {
    use super::*;
    use homelinter_model::asset_kind::AssetKind;

    fn mv_suggestion() -> Suggestion {
        let mut s = Suggestion::new_move(
            AssetKind::Document,
            std::path::Path::new("/home/alice/Downloads/a.pdf"),
            std::path::Path::new("/home/alice/Documents/a.pdf"),
            "Moved to documents.".into(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        s.status = SuggestionStatus::Pending;
        s
    }

    #[test]
    fn posix_export_quotes_paths_and_aborts() {
        let mut s = mv_suggestion();
        s.target = "/home/alice/O'Reilly/a.pdf".into();
        let script = export_host(std::slice::from_ref(&s)).unwrap();
        assert!(script.starts_with("#!/bin/sh"));
        assert!(script.contains("abort"));
        assert!(script.contains("'/home/alice/O'\\''Reilly/a.pdf'"));
        assert!(script.contains("mv -n"));
    }

    #[test]
    fn posix_export_refuses_cross_fs_moves_at_run_time() {
        let s = mv_suggestion();
        let script = export_script(std::slice::from_ref(&s), "linux").unwrap();
        assert!(script.contains("cross-filesystem move is not supported"));
        assert!(!script.contains("cp -a"), "no unverified copy fallback");
        assert!(!script.contains(".homelinter-partial"), "no partial copy");
    }

    #[test]
    fn delete_without_hash_refused() {
        let s = Suggestion::new_delete(
            AssetKind::Document,
            std::path::Path::new("/x/y.bin"),
            "dup".into(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        assert!(export_host(std::slice::from_ref(&s)).is_err());
    }

    #[test]
    fn posix_delete_hashes_with_a_portable_tool() {
        let mut s = Suggestion::new_delete(
            AssetKind::Document,
            std::path::Path::new("/x/y.bin"),
            "dup".into(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        s.provenance.full_hash = Some([0xab; 32]);
        let script = export_script(std::slice::from_ref(&s), "linux").unwrap();
        assert!(script.contains("command -v sha256sum"));
        assert!(script.contains("shasum -a 256"));
        assert!(script.contains(&hex::encode([0xab; 32])));
    }

    fn keeper_delete(keeper: &str, duplicate: &str, link: &str, replacement: &str) -> Suggestion {
        use homelinter_model::suggestion::{DependentOpType, DependentOperation, Provenance};
        let mut s = Suggestion::new_delete(
            AssetKind::Document,
            std::path::Path::new(duplicate),
            "dup".into(),
            std::collections::BTreeMap::from([(
                "duplicate_of".to_string(),
                serde_json::Value::String(keeper.into()),
            )]),
            vec![DependentOperation {
                op_type: DependentOpType::RepairSymlink,
                link_path: link.into(),
                recorded_target: keeper.into(),
                replacement_target: replacement.into(),
                recorded_target_relative: false,
                provenance: Provenance {
                    link_resolved_target: Some(keeper.into()),
                    link_raw_relative: Some(false),
                    ..Default::default()
                },
            }],
            Default::default(),
        );
        s.provenance.full_hash = Some([0xcd; 32]);
        s
    }

    #[test]
    fn posix_export_moves_the_keeper_before_repointing_repairs_at_it() {
        let keeper = "/home/alice/Downloads/zeta.bin";
        let keeper_dst = "/home/alice/Pictures/zeta.bin";
        let mut mv = Suggestion::new_move(
            AssetKind::Document,
            std::path::Path::new(keeper),
            std::path::Path::new(keeper_dst),
            String::new(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        let del = keeper_delete(
            keeper,
            "/home/alice/Downloads/beta.bin",
            "/home/alice/link.bin",
            keeper,
        );
        // Deliberately delete-first input order: the export must reorder.
        let script = export_script(&[del, mv.clone()], "linux").unwrap();
        let move_at = script.find("mv -n").expect("keeper move");
        let delete_at = script.find("rm -f").expect("duplicate delete");
        let repair_at = script.find("ln -sfn").expect("repair");
        assert!(move_at < delete_at, "{script}");
        assert!(delete_at < repair_at, "{script}");
        assert!(
            script.contains(&format!("ln -sfn '{keeper_dst}'")),
            "{script}"
        );
        assert!(!script.contains(&format!("ln -sfn '{keeper}'")), "{script}");

        // Without the keeper's move the repair keeps the original path.
        mv.status = SuggestionStatus::Rejected;
        let script = export_script(
            &[
                keeper_delete(
                    keeper,
                    "/home/alice/Downloads/beta.bin",
                    "/home/alice/link.bin",
                    keeper,
                ),
                mv,
            ],
            "linux",
        )
        .unwrap();
        assert!(script.contains(&format!("ln -sfn '{keeper}'")), "{script}");
    }

    #[test]
    fn windows_export_escapes_single_quotes() {
        let mut s = mv_suggestion();
        s.target = "/home/O'Brien/a.pdf".into();
        s.new_path = Some("/home/O'Brien/Documents/a.pdf".into());
        let script = export_script(std::slice::from_ref(&s), "windows").unwrap();
        assert!(script.contains("'/home/O''Brien/a.pdf'"));
        assert!(script.contains("'/home/O''Brien/Documents/a.pdf'"));
        assert!(!script.contains("'/home/O'Brien/"));
    }

    #[test]
    fn windows_export_notes_reparse_seam() {
        let s = mv_suggestion();
        let script = export_script(std::slice::from_ref(&s), "windows").unwrap();
        assert!(script.contains("Move-Item"));
    }
}
