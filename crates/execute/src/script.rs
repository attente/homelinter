//! Platform script export: POSIX shell (linux, macOS) and PowerShell
//! (Windows) scripts built from a validated execution plan.
//!
//! The script repeats the executor's safe defaults: it aborts on unexpected
//! source or destination state rather than overwriting, performs moves with
//! no-clobber semantics, re-verifies content hashes before deletes that
//! have one on record, and runs dependent symlink repairs only after their
//! parent succeeds. Cross-filesystem moves degrade to the same shape as the
//! native verified copy protocol using host utilities; the native executor
//! remains authoritative for safety, and a script can never weaken it
//! because it only ever runs the validated plan.

use std::path::Path;

use homelinter_model::config::platform_name;
use homelinter_model::suggestion::{Suggestion, SuggestionStatus, SuggestionType};

/// Render an export for the host platform from validated suggestions.
/// Suggestions must already be batch-validated; rejected suggestions are
/// skipped by callers and never appear here.
pub fn export_script(suggestions: &[Suggestion], platform: &str) -> Result<String, String> {
    match platform {
        "linux" | "macos" => export_posix(suggestions),
        "windows" => export_powershell(suggestions),
        other => Err(format!("unsupported export platform: {other}")),
    }
}

/// Export for the host platform.
pub fn export_host(suggestions: &[Suggestion]) -> Result<String, String> {
    export_script(suggestions, platform_name())
}

fn export_posix(suggestions: &[Suggestion]) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("#!/bin/sh\n");
    out.push_str("# Generated by homelinter. Do not edit; re-export instead.\n");
    out.push_str("set -eu\n");
    out.push_str("abort() { echo \"homelinter: $*\" >&2; exit 1; }\n\n");

    for s in suggestions {
        if s.status == SuggestionStatus::Rejected {
            continue;
        }
        match s.suggestion_type {
            SuggestionType::Move => export_posix_move(s, &mut out)?,
            SuggestionType::Delete => export_posix_delete(s, &mut out)?,
        }
        for dep in &s.dependent_operations {
            let link = shell_quote(&dep.link_path);
            let repl = shell_quote(&dep.replacement_target);
            out.push_str(&format!(
                "[ -L {link} ] || abort \"link changed: {link}\"\n"
            ));
            out.push_str(&format!("ln -sfn {repl} {link}\n"));
        }
        out.push('\n');
    }
    Ok(out)
}

fn export_posix_move(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let src = shell_quote(&s.target);
    let dst = s
        .new_path
        .as_ref()
        .ok_or_else(|| format!("move suggestion {} lacks new_path", s.id))?;
    let dst_q = shell_quote(dst);
    let parent = Path::new(dst)
        .parent()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_default();
    let parent_q = shell_quote(&parent);
    out.push_str(&format!(
        "# {}\n",
        s.reason.replace('\n', " ").replace('#', "")
    ));
    out.push_str(&format!(
        "[ -e {src} ] || abort \"source missing: {src}\"\n"
    ));
    out.push_str(&format!(
        "[ ! -e {dst_q} ] || abort \"destination exists: {dst_q}\"\n"
    ));
    out.push_str(&format!("mkdir -p {parent_q}\n"));
    // Same-filesystem guard: when the source and destination are on
    // different filesystems `mv` would copy then delete, which is exactly
    // the verified-copy protocol the native executor follows.
    out.push_str(&format!(
        "if [ \"$(stat -c %d {src} 2>/dev/null || stat -f %d {src})\" = \"$(stat -c %d {parent_q} 2>/dev/null || stat -f %d {parent_q})\" ]; then\n"
    ));
    out.push_str(&format!(
        "  mv -n {src} {dst_q} || abort \"move failed: {src}\"\n"
    ));
    out.push_str(&format!(
        "  [ ! -e {src} ] || abort \"source remains: {src}\"\n"
    ));
    out.push_str("else\n");
    out.push_str(&format!("  cp -a {src} {dst_q}.homelinter-partial\n"));
    out.push_str(&format!(
        "  mv -n {dst_q}.homelinter-partial {dst_q} || abort \"publish failed: {dst_q}\"\n"
    ));
    out.push_str(&format!("  rm -rf {src}\n"));
    out.push_str("fi\n");
    Ok(())
}

fn export_posix_delete(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let target = shell_quote(&s.target);
    out.push_str(&format!(
        "# {}\n",
        s.reason.replace('\n', " ").replace('#', "")
    ));
    out.push_str(&format!(
        "[ -e {target} ] || abort \"delete target missing: {target}\"\n"
    ));
    // Delete requires the full-content hash recorded at analysis; without
    // it the native executor refuses and the export refuses too.
    if let Some(hash_hex) = s.provenance.full_hash {
        let expected = hex::encode(hash_hex);
        out.push_str(&format!("actual=$(sha256sum {target} | cut -d' ' -f1)\n"));
        out.push_str(&format!(
            "[ \"$actual\" = \"{expected}\" ] || abort \"content changed since analysis: {target}\"\n"
        ));
    } else {
        return Err(format!(
            "delete suggestion {} has no recorded content hash; export refused",
            s.id
        ));
    }
    out.push_str(&format!("rm -f {target}\n"));
    Ok(())
}

fn export_powershell(suggestions: &[Suggestion]) -> Result<String, String> {
    let mut out = String::new();
    out.push_str("# Generated by homelinter. Do not edit; re-export instead.\n");
    out.push_str("$ErrorActionPreference = 'Stop'\n");
    out.push_str("function Abort([string]$msg) { Write-Error \"homelinter: $msg\"; exit 1 }\n\n");
    for s in suggestions {
        if s.status == SuggestionStatus::Rejected {
            continue;
        }
        match s.suggestion_type {
            SuggestionType::Move => export_powershell_move(s, &mut out)?,
            SuggestionType::Delete => export_powershell_delete(s, &mut out)?,
        }
        for dep in &s.dependent_operations {
            // Windows junction/reparse repair is a documented seam; the
            // script aborts rather than guessing at link semantics.
            out.push_str(&format!(
                "# repair_symlink {dep_link} -> {dep_repl} (reparse-point repair is a seam on Windows; run homelinter instead)\n",
                dep_link = dep.link_path,
                dep_repl = dep.replacement_target,
            ));
        }
        out.push('\n');
    }
    Ok(out)
}

fn export_powershell_move(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let dst = s
        .new_path
        .as_ref()
        .ok_or_else(|| format!("move suggestion {} lacks new_path", s.id))?;
    let parent = Path::new(dst)
        .parent()
        .map(|p| p.to_string_lossy().into_owned())
        .unwrap_or_default();
    out.push_str(&format!("# {}\n", s.reason.replace('\n', " ")));
    out.push_str(&format!(
        "if (-not (Test-Path -LiteralPath '{src}')) {{ Abort 'source missing: {src}' }}\n",
        src = s.target
    ));
    out.push_str(&format!(
        "if (Test-Path -LiteralPath '{dst}') {{ Abort 'destination exists: {dst}' }}\n",
        dst = dst
    ));
    out.push_str(&format!(
        "New-Item -ItemType Directory -Force -Path '{parent}' | Out-Null\n",
        parent = parent
    ));
    out.push_str(&format!(
        "Move-Item -LiteralPath '{src}' -Destination '{dst}'\n",
        src = s.target
    ));
    Ok(())
}

fn export_powershell_delete(s: &Suggestion, out: &mut String) -> Result<(), String> {
    let Some(hash_hex) = s.provenance.full_hash else {
        return Err(format!(
            "delete suggestion {} has no recorded content hash; export refused",
            s.id
        ));
    };
    let expected = hex::encode(hash_hex);
    out.push_str(&format!("# {}\n", s.reason.replace('\n', " ")));
    out.push_str(&format!(
        "if (-not (Test-Path -LiteralPath '{src}')) {{ Abort 'delete target missing: {src}' }}\n",
        src = s.target
    ));
    out.push_str(&format!(
        "$h = (Get-FileHash -Algorithm SHA256 -LiteralPath '{src}').Hash.ToLower()\n",
        src = s.target
    ));
    out.push_str(&format!(
        "if ($h -ne '{expected}') {{ Abort 'content changed since analysis: {src}' }}\n",
        src = s.target
    ));
    out.push_str(&format!(
        "Remove-Item -LiteralPath '{src}'\n",
        src = s.target
    ));
    Ok(())
}

/// Single-quote a path for POSIX shells: `'` becomes `'\''`.
fn shell_quote(p: &str) -> String {
    format!("'{}'", p.replace('\'', "'\\''"))
}

#[cfg(test)]
mod tests {
    use super::*;
    use homelinter_model::asset_kind::AssetKind;

    fn mv_suggestion() -> Suggestion {
        let mut s = Suggestion::new_move(
            AssetKind::Document,
            std::path::Path::new("/home/alice/Downloads/a.pdf"),
            std::path::Path::new("/home/alice/Documents/a.pdf"),
            "Moved to documents.".into(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        s.status = SuggestionStatus::Pending;
        s
    }

    #[test]
    fn posix_export_quotes_paths_and_aborts() {
        let mut s = mv_suggestion();
        s.target = "/home/alice/O'Reilly/a.pdf".into();
        let script = export_host(std::slice::from_ref(&s)).unwrap();
        assert!(script.starts_with("#!/bin/sh"));
        assert!(script.contains("abort"));
        assert!(script.contains("'/home/alice/O'\\''Reilly/a.pdf'"));
        assert!(script.contains("mv -n"));
    }

    #[test]
    fn delete_without_hash_refused() {
        let s = Suggestion::new_delete(
            AssetKind::Document,
            std::path::Path::new("/x/y.bin"),
            "dup".into(),
            Default::default(),
            Vec::new(),
            Default::default(),
        );
        assert!(export_host(std::slice::from_ref(&s)).is_err());
    }

    #[test]
    fn windows_export_notes_reparse_seam() {
        let s = mv_suggestion();
        let script = export_script(std::slice::from_ref(&s), "windows").unwrap();
        assert!(script.contains("Move-Item"));
    }
}
